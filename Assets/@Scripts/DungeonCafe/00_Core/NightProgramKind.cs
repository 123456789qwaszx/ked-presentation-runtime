/// <summary>
/// 밤에 메이드 한 명에게 적용할 수 있는 처리 방식.
/// </summary>
public enum NightProgramKind
{
    None = 0,

    // 위로와 치료. 붕괴도를 안전하게 낮추지만 숙련 경험은 거의 늘지 않는다.
    Care = 10,

    // 관리하의 의도적 붕괴. 낮의 요구를 통제된 형태로 재구성해 끝까지 완료시킨다.
    // 붕괴도를 일시적으로 한계까지 끌어올린 뒤 회수하며, 해당 축의 숙련 경험을 크게 얻는다.
    ManagedRelease = 20,
}
