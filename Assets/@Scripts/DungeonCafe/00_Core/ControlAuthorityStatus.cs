/// <summary>
/// 접객 관리 프로토콜에 따라 관리자에게 위임된 신체 운용 권한의 현재 상태.
/// Lost 이후에는 플레이어의 승인 입력이 더 이상 세션에 반영되지 않는다.
/// </summary>
public enum ControlAuthorityStatus
{
    // 정상 위임. 메이드가 제안하고 관리자가 승인한다.
    Delegated = 0,

    // 한계 근접. 승인 흐름은 유지되지만 긴급 정지 경고가 노출된다.
    Strained = 10,

    // 한계 초과. 관리자 통제 신호가 거부되었고, 이후는 자동 사건으로 진행된다.
    Lost = 20,
}
